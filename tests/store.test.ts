    expect(app.checklist[0]?.required).toBe(true);
    expect(store.getOpportunity(oppId)!.application).toEqual({ id: app.id, status: 'ready' });
    expect(store.getApplicationByOpportunity(oppId)?.id).toBe(app.id);

    const updated = store.updateApplication(app.id, { priceTotal: 1234.5, includeRates: true, missing: ['A price'], editedByUser: true, remindedAt: '2026-06-16T00:00:00Z' }, later(1))!;
