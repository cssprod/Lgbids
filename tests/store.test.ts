// Summer dates: Pacific time is UTC-7 whichever time zone rules the runtime has.
const now = new Date('2026-06-15T20:00:00Z');
const later = (hours: number) => new Date(now.getTime() + hours * 3_600_000);

let store: ChangeStore;

function addSource(id: string, name = id) {
  store.insertSource({ id, name, kind: 'html_list', enabled: true, builtin: false, notes: '', config: sourceConfigSchema.parse({}) }, now);
}

function raw(overrides: Partial<RawOpportunity> = {}): RawOpportunity {
  return {
    externalId: 'n-1',
    title: 'RFQ 2026-041 Boulevard Mowing Services',
    url: 'https://bids.example/n-1',
    organization: 'District of Saanich',
    closing: { iso: '2026-07-09T21:00:00Z', precision: 'datetime' },
    closingRaw: 'July 9, 2026 2:00 PM',
    ...overrides,
  };
}

const analysis: Analysis = {
  relevance: 80,
  matchedTerms: ['mowing'],
  services: ['vegetation'],
  area: 'yes',
  areaMatch: 'Saanich',
  reasons: [],
  requirements: [],
  pricing: 'lump_sum',
  alsoListed: [],
};

function analyse(id: number, decision: Decision, extra: Partial<AnalysisSave> = {}) {
  store.saveAnalysis(
    id,
    { noticeType: 'RFQ', score: 70, decision, analysis, submissionMethod: 'email', submissionEmail: 'bids@saanich.example', submissionUrl: '', ...extra },
    now,
  );
}

function appData(opportunityId: number, overrides: Partial<ApplicationCreate> = {}): ApplicationCreate {
  return {
    opportunityId,
    status: 'ready',
    channel: 'email',
    toEmail: 'bids@saanich.example',
    ccEmail: '',
    subject: 'Submission',
    body: 'Hello',
    includeRates: false,
    checklist: [{ key: 'forms', label: 'Forms', detail: '', done: false, required: true }],
    documentIds: [],
    missing: [],
    autoGenerated: true,
    ...overrides,
  };
}

