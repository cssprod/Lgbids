describe('sources, runs, events, sessions, settings rows', () => {
  it('seeds without overwriting edits and records health', () => {
    store.seedSources([{ id: 'a', name: 'Default A', kind: 'rss', notes: '', config: sourceConfigSchema.parse({}) }, { id: 'c', name: 'C', kind: 'rss', notes: '', config: sourceConfigSchema.parse({}) }], now);
    expect(store.getSource('a')?.name).toBe('Source A');
    expect(store.getSource('c')).toMatchObject({ builtin: true, enabled: true, lastStatus: 'never' });
    store.recordSourceRun('c', { status: 'error', message: 'Down', itemCount: null }, now);
    store.recordSourceRun('c', { status: 'error', message: 'Down', itemCount: null }, now);
    expect(store.getSource('c')).toMatchObject({ consecutiveFailures: 2, lastOkAt: null, lastStatus: 'error' });
    store.recordSourceRun('c', { status: 'ok', message: '', itemCount: 4 }, later(1));
    expect(store.getSource('c')).toMatchObject({ consecutiveFailures: 0, lastOkAt: '2026-06-15T21:00:00Z', lastItemCount: 4 });

    // A built-in that now refuses automated reading (forced off): new installs
    // get it off, existing ones are switched off with the new note, and (as it
    // was never edited) its address follows the new default (COV-11).
    store.seedSources([{ id: 'c', name: 'C', kind: 'rss', notes: 'Turned off: robots.txt.', config: sourceConfigSchema.parse({ url: 'https://new.example/feed' }), enabled: false, forceOff: true }, { id: 'd', name: 'D', kind: 'rss', notes: 'Off.', config: sourceConfigSchema.parse({}), enabled: false }], now);
    expect(store.getSource('c')).toMatchObject({ enabled: false, notes: 'Turned off: robots.txt.' });
    expect(store.getSource('c')?.config.url).toBe('https://new.example/feed');
    expect(store.getSource('d')).toMatchObject({ builtin: true, enabled: false });
    expect(store.getSource('a')?.name).toBe('Source A');

    // One that merely ships off stays on once the user turns it on, across restarts.
    store.updateSource('d', { enabled: true }, now);
    store.seedSources([{ id: 'd', name: 'D', kind: 'rss', notes: 'Off.', config: sourceConfigSchema.parse({}), enabled: false }], later(2));
    expect(store.getSource('d')?.enabled).toBe(true);
    // A forced-off one is switched off again even if the user turned it on.
    store.updateSource('c', { enabled: true }, now);
    store.seedSources([{ id: 'c', name: 'C', kind: 'rss', notes: 'Turned off: robots.txt.', config: sourceConfigSchema.parse({}), enabled: false, forceOff: true }], later(2));
    expect(store.getSource('c')?.enabled).toBe(false);

    store.setSourceState('c', { etag: 'x' });
    expect(store.getSourceState('c')).toEqual({ etag: 'x' });
    store.clearSourceStates();
    expect(store.getSourceState('c')).toEqual({});
    expect(store.updateSource('c', { enabled: false }, now)?.enabled).toBe(false);
    expect(store.deleteSource('c')).toBe(true);
    expect(store.deleteSource('c')).toBe(false);
  });

  it('records runs and fails stale ones', () => {
    const run = store.startRun('manual', now);
    expect(run.status).toBe('running');
    store.failStaleRuns(later(1));
    expect(store.latestRun()).toMatchObject({ status: 'error', error: 'The app stopped while this run was in progress.', finishedAt: '2026-06-15T21:00:00Z' });
    const second = store.startRun('cli', now);
    const done = store.finishRun(second.id, 'ok', { sources: [], found: 1, added: 1, analysed: 1, suitable: 0, drafted: 0, sent: 0, expired: 0 }, '', now);
    expect(done.stats?.found).toBe(1);
    expect(store.listRuns(10).map((r) => r.id)).toEqual([second.id, run.id]);
    store.addEvent({ level: 'info', kind: 'run', message: 'Started.', opportunityId: null, applicationId: null, runId: run.id }, now);
    store.addEvent({ level: 'warn', kind: 'source', message: 'Slow.', opportunityId: null, applicationId: null, runId: null }, now);
    expect(store.listEvents(1)[0]?.message).toBe('Slow.');
    // Pruning removes old history but never a run still in progress.
    const running = store.startRun('manual', now);
    expect(store.pruneHistory('2026-06-16T00:00:00Z')).toEqual({ events: 2, runs: 2 });
    expect(store.listRuns(10).map((r) => r.id)).toEqual([running.id]);
  });

  it('expires sessions', () => {
    store.createSession('tok', later(24), now);
    expect(store.sessionValid('tok', later(23))).toBe(true);
    expect(store.sessionValid('tok', later(25))).toBe(false);
    expect(store.sessionValid('nope', now)).toBe(false);
    store.deleteSession('tok');
    expect(store.sessionValid('tok', now)).toBe(false);
  });
});

describe('settings service', () => {
  it('fills defaults and validates', () => {
    const settings = createSettings(store, {}, () => now);
    expect(settings.getAutomation().mode).toBe('prepare');
    expect(settings.getProfile().province).toBe('BC');
    expect(settings.getRegion()).toEqual(defaultRegion());
    expect(() => settings.setAutomation({ mode: 'sometimes' })).toThrow(ZodError);
    expect(settings.setAutomation({ mode: 'auto' }).dailySendCap).toBe(5);
    expect(settings.getAutomation().mode).toBe('auto');
  });

  it('asks for recomputation when settings change', () => {
    const settings = createSettings(store, {}, () => now);
    const id = store.upsertOpportunity('a', raw(), false, now).id;
    analyse(id, 'review');
    store.setSourceState('a', { etag: 'x' });
    settings.setProfile({ legalName: 'Green Co' });
    expect(store.getOpportunity(id)!.analysedAt).toBeNull();
    expect(store.getSourceState('a')).toEqual({ etag: 'x' });
    settings.setRegion({ places: ['Sooke'] });
    expect(store.getSourceState('a')).toEqual({});
    expect(settings.getRegion().places).toEqual(['Sooke']);
    expect(settings.setRegion({})).toEqual(defaultRegion());
    settings.setRegion({ places: ['Sooke'] });
    expect(settings.resetRegion()).toEqual(defaultRegion());
    expect(store.getSetting('region')).toBeUndefined();
  });

  it('keeps the stored password and resets verification on connection changes', () => {
    const settings = createSettings(store, {}, () => now);
    settings.setEmail({ host: 'smtp.example', user: 'me', pass: 'secret', verifiedAt: '2026-06-15T20:00:00Z' });
    expect(settings.getEmail().verifiedAt).toBeNull();
    settings.setEmail({ host: 'smtp.example', user: 'me', pass: '', verifiedAt: '2026-06-15T20:00:00Z' });
    expect(settings.getEmail()).toMatchObject({ pass: 'secret', verifiedAt: '2026-06-15T20:00:00Z' });
    settings.setEmail({ host: 'smtp.example', user: 'me', pass: '', fromName: 'Green Co' });
    expect(settings.getEmail()).toMatchObject({ fromName: 'Green Co', verifiedAt: '2026-06-15T20:00:00Z' });
    // OPS-5: a saved password is never carried over to a different host.
    settings.setEmail({ host: 'smtp.other.example', user: 'me', pass: '' });
    expect(settings.getEmail()).toMatchObject({ pass: '', verifiedAt: null });
    expect(() => settings.setEmail({ port: 0 })).toThrow(ZodError);
  });

  it('overlays SMTP environment variables', () => {
    const env = { SMTP_HOST: 'mail.example', SMTP_PORT: '465', SMTP_SECURE: 'true', SMTP_PASS: 'envpass', SMTP_FROM_EMAIL: 'bids@green.example' };
    const settings = createSettings(store, env, () => now);
    settings.setEmail({ host: 'smtp.example', user: 'me', pass: 'secret' });
    expect(settings.getEmail()).toMatchObject({ host: 'mail.example', port: 465, secure: true, user: 'me', pass: 'envpass', fromEmail: 'bids@green.example' });
    expect(emailFromEnvironment(env)).toEqual(['host', 'port', 'secure', 'pass', 'fromEmail']);
    expect(emailFromEnvironment({ SMTP_PORT: 'abc' })).toEqual([]);
  });
});

