describe('fully automatic mode', () => {
  const auto = { mode: 'auto', autoSendTypes: ['RFQ', 'OTHER'], autoSendThreshold: 75, dailySendCap: 5 };

  it('sends only what passes every guardrail', async () => {
    const env = makeEnv({ smtp: true, automation: auto });
    const pipeline = createPipeline(env.deps);
    const first = await pipeline.run('manual');
    // Only the rate-based quotation with nothing else outstanding goes out unattended:
    // automatic mode waives the "I have read the bid documents" tick and nothing more.
    expect(first.stats!.sent).toBe(1);
    expect(sentTo(env)).toEqual(['quotes@saanich.example']);
    expect(appFor(env, 'Memorial Park').status).toBe('needs_input');

    // A person enters the price for the lump-sum job.
    tick(env, 'Memorial Park', ['pricing'], 4800);
    // Price entered, but the buyer's form is still unticked.
    tick(env, 'Regional Parks Mowing', ['documents']);
    // Ready, but the address was changed by hand: never sent automatically.
    tick(env, 'Cemetery Grounds', ['documents', 'pricing'], 3200);
    env.store.updateApplication(appFor(env, 'Cemetery Grounds').id, { toEmail: 'someone.else@metchosin.example', editedByUser: true }, env.clock.now);

    const second = await pipeline.run('manual');
    expect(second.stats!.sent).toBe(1);
    expect(sentTo(env).sort()).toEqual(['bids@esquimalt.example', 'quotes@saanich.example']);
    expect(appFor(env, 'Yard Maintenance Services')).toMatchObject({ status: 'submitted', submittedVia: 'auto-email' });
    expect(appFor(env, 'Regional Parks Mowing').status).toBe('needs_input');
    expect(appFor(env, 'Cemetery Grounds').status).toBe('ready');
    const refused = await pipeline.send(appFor(env, 'Cemetery Grounds').id, { auto: true });
    expect(refused.ok).toBe(false);
    expect(refused.error).toMatch(/recipient address was changed/);
    expect(appFor(env, 'Cemetery Grounds').status).toBe('ready');
  });

  it('honours the score threshold and allowed notice types', async () => {
    const env = makeEnv({ smtp: true, automation: { ...auto, autoSendTypes: ['RFSO'] } });
    const pipeline = createPipeline(env.deps);
    await pipeline.run('manual');
    const id = tick(env, 'Yard Maintenance Services', ['documents']);
    expect(pipeline.reassess(id).status).toBe('ready');
    expect((await pipeline.send(id, { auto: true })).error).toMatch(/type of notice/);
    env.deps.settings.setAutomation({ ...env.deps.settings.getAutomation(), autoSendTypes: ['OTHER'], autoSendThreshold: 100 });
    expect((await pipeline.send(id, { auto: true })).error).toMatch(/below your automatic-sending threshold/);
    expect(env.sent).toHaveLength(0);
    expect(env.store.getApplication(id)!.status).toBe('ready');
  });

  it('stops at the daily cap', async () => {
    const env = makeEnv({ smtp: true, automation: { ...auto, dailySendCap: 1 } });
    const pipeline = createPipeline(env.deps);
    const firstRun = await pipeline.run('manual');
    expect(firstRun.stats!.sent).toBe(1);
    tick(env, 'Memorial Park', ['documents', 'pricing'], 4800);
    const run = await pipeline.run('manual');
    expect(run.stats!.sent).toBe(0);
    expect(env.sent).toHaveLength(1);
    const waiting = env.store.listApplications({ status: ['ready'] }).filter((a) => a.channel === 'email');
    expect(waiting).toHaveLength(1);
    const refused = await pipeline.send(waiting[0]!.id, { auto: true });
    expect(refused.error).toMatch(/daily limit/);
    expect(env.store.getApplication(waiting[0]!.id)!.status).toBe('ready');
    // A person can still send it.
    expect((await pipeline.send(waiting[0]!.id, { auto: false })).ok).toBe(true);
  });

  it('never re-sends a submission left "sending" by a crash', async () => {
    const env = makeEnv({ smtp: true, automation: { ...auto, mode: 'prepare' } });
    await createPipeline(env.deps).run('manual');
    const id = appFor(env, 'Yard Maintenance Services').id;
    expect(env.store.transitionApplication(id, ['needs_input', 'ready'], 'sending', env.clock.now)).toBe(true);
    env.deps.settings.setAutomation({ ...env.deps.settings.getAutomation(), mode: 'auto' });

    const restarted = createPipeline(env.deps);
    expect(env.store.getApplication(id)).toMatchObject({ status: 'failed', error: 'The app stopped while this was being sent. Check your sent mail before sending again.' });
    await restarted.run('manual');
    expect(sentTo(env)).not.toContain('quotes@saanich.example');
    expect(env.store.getApplication(id)!.status).toBe('failed');
  });

  it('marks a submission failed when the mail server refuses it, and lets a person retry', async () => {
    const env = makeEnv({ smtp: true });
    const pipeline = createPipeline(env.deps);
    await pipeline.run('manual');
    const id = tick(env, 'Yard Maintenance Services', ['documents']);
    pipeline.reassess(id);
    env.mailFails.value = true;
    const failed = await pipeline.send(id, { auto: false });
    expect(failed).toEqual({ ok: false, error: 'The mail server refused the message.' });
    expect(env.store.getApplication(id)).toMatchObject({ status: 'failed', error: 'The mail server refused the message.' });
    expect(env.store.listEvents(20).some((e) => e.kind === 'send_failed' && e.level === 'error')).toBe(true);
    env.mailFails.value = false;
    expect((await pipeline.send(id, { auto: true })).ok).toBe(false);
    expect((await pipeline.send(id, { auto: false })).ok).toBe(true);
    expect(env.store.getApplication(id)!.status).toBe('submitted');
  });
});

