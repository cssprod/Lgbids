// These steps tell one story on one shared env (run, draft, send, refuse,
// expire), so they keep their written order even with --sequence.shuffle.
describe('a run over the sample sites', { shuffle: false }, () => {
  let env: Env;
  let first: Awaited<ReturnType<ReturnType<typeof createPipeline>['run']>>;

  beforeAll(async () => {
    env = makeEnv({ smtp: true });
    first = await createPipeline(env.deps).run('manual');
  });

  it('finishes ok with per-source statistics', () => {
    expect(first.status).toBe('ok');
    expect(first.finishedAt).not.toBeNull();
    const stats = first.stats!;
    expect(stats.sources).toHaveLength(8);
    for (const s of stats.sources) {
      expect(s.status, s.name).toBe('ok');
      expect(s.found, s.name).toBeGreaterThan(0);
      expect(s.added, s.name).toBe(s.found);
      expect(s.ms).toBeGreaterThanOrEqual(0);
    }
    expect(stats.found).toBe(stats.sources.reduce((n, s) => n + s.found, 0));
    expect(stats.suitable).toBeGreaterThan(0);
    expect(stats.drafted).toBe(stats.suitable);
    expect(env.store.getSource('crd')).toMatchObject({ lastStatus: 'ok', lastItemCount: 4 });
  });

  it('keeps one canonical row for a notice listed on three sources', () => {
    const boulevard = find(env, 'Boulevard and Median');
    expect(boulevard.duplicateOf).toBeNull();
    expect(boulevard.analysis!.alsoListed).toHaveLength(2);
    expect(env.store.duplicatesOf(boulevard.id)).toHaveLength(2);
  });

  it('rules out work outside Greater Victoria', () => {
    for (const [fragment, place] of [
      ['Salt Spring Island Parks Mowing', 'Salt Spring'],
      ['Prince George', 'Prince George'],
      ['Kelowna Courthouse', 'Kelowna'],
      ['Parks Mowing Services', 'Nanaimo'],
    ] as const) {
      const opp = find(env, fragment);
      expect(opp.decision, fragment).toBe('unsuitable');
      expect(opp.analysis!.reasons.some((r) => r.tone === 'block' && r.text.includes(place)), fragment).toBe(true);
      expect(env.store.getApplicationByOpportunity(opp.id), fragment).toBeUndefined();
    }
  });

  it('rules out a consulting master plan and a notice of intent, with the reason', () => {
    const plan = find(env, 'Master Plan');
    expect(plan.decision).toBe('unsuitable');
    expect(plan.analysis!.reasons.some((r) => r.tone === 'block' && /design|consult/i.test(r.text))).toBe(true);
    const noi = find(env, 'Notice of Intent');
    expect(noi.decision).toBe('unsuitable');
    expect(noi.noticeType).toBe('NOI');
    expect(noi.analysis!.reasons.some((r) => r.tone === 'block' && /intent/i.test(r.text))).toBe(true);
  });

  it('finds the e-mail submission address and rates pricing on a notice page', () => {
    const yard = find(env, 'Yard Maintenance Services');
    expect(yard).toMatchObject({ decision: 'suitable', submissionMethod: 'email', submissionEmail: 'quotes@saanich.example' });
    expect(yard.analysis!.pricing).toBe('rates');
    expect(yard.detailFetchedAt).not.toBeNull();
  });

  it('reads the submission address from a linked PDF', () => {
    const mowing = find(env, 'Regional Parks Mowing');
    expect(mowing.documentsReadAt).not.toBeNull();
    expect(mowing.documentText).toContain('quotes@crd.example');
    expect(mowing).toMatchObject({ submissionMethod: 'email', submissionEmail: 'quotes@crd.example' });
  });

  it('drafts submissions in prepare mode and sends nothing', async () => {
    expect(env.sent).toHaveLength(0);
    const yard = appFor(env, 'Yard Maintenance Services');
    expect(yard).toMatchObject({ channel: 'email', toEmail: 'quotes@saanich.example', autoGenerated: true });
    expect(appFor(env, 'Boulevard and Median').channel).toBe('portal');
    expect(env.store.listEvents(100).some((e) => e.kind === 'drafted' && e.message.startsWith('Drafted a submission for'))).toBe(true);

    // Even a complete draft waits for the user in prepare mode.
    tick(env, 'Yard Maintenance Services', ['documents']);
    const second = await createPipeline(env.deps).run('manual');
    expect(second.stats!.sent).toBe(0);
    expect(env.store.getApplication(yard.id)!.status).toBe('ready');
    expect(env.sent).toHaveLength(0);
  });

  it('does not add duplicates on a second run and re-uses the CSV ETag', async () => {
    const before = env.store.countOpportunities(env.clock.now).all;
    const again = await createPipeline(env.deps).run('manual');
    expect(again.stats!.added).toBe(0);
    expect(env.store.countOpportunities(env.clock.now).all).toBe(before);
    const csv = again.stats!.sources.find((s) => s.sourceId === 'cb-csv')!;
    expect(csv).toMatchObject({ status: 'ok', found: 0 });
    expect(csv.message).toMatch(/not changed|no change/i);
    expect(env.store.getSource('cb-csv')!.lastItemCount).toBe(3);
  });

  it('sends a ready submission by hand once, with the package attached', async () => {
    const pipeline = createPipeline(env.deps);
    const id = appFor(env, 'Yard Maintenance Services').id;
    expect(pipeline.reassess(id).status).toBe('ready');
    const result = await pipeline.send(id, { auto: false });
    expect(result).toEqual({ ok: true, error: '' });
    expect(env.sent).toHaveLength(1);
    const mail = env.sent[0]!;
    expect(mail.to).toEqual(['quotes@saanich.example']);
    expect(mail.bcc).toEqual(['office@garryoak.example']);
    const pdf = mail.attachments.find((a) => a.contentType === 'application/pdf')!;
    expect(pdf.filename).toMatch(/\.pdf$/);
    expect(pdf.content.subarray(0, 5).toString()).toBe('%PDF-');
    expect(env.store.getApplication(id)).toMatchObject({ status: 'submitted', submittedVia: 'email', submissionRef: '<1@test.example>' });

    const twice = await pipeline.send(id, { auto: false });
    expect(twice.ok).toBe(false);
    expect(twice.error).toMatch(/already/);
    expect(env.sent).toHaveLength(1);
  });

  it('refuses a draft that still needs input', async () => {
    const pipeline = createPipeline(env.deps);
    const result = await pipeline.send(appFor(env, 'Cemetery Grounds').id, { auto: false });
    expect(result.ok).toBe(false);
    expect(env.sent).toHaveLength(1);
  });

  it('builds the package PDF on request', async () => {
    const pkg = await createPipeline(env.deps).packagePdf(appFor(env, 'Regional Parks Mowing').id);
    expect(pkg.filename).toMatch(/\.pdf$/);
    expect(pkg.content.subarray(0, 5).toString()).toBe('%PDF-');
  });

  it('closes opportunities past their closing time and expires unsent drafts', async () => {
    const sentId = appFor(env, 'Yard Maintenance Services').id;
    // Moves this env's clock two months on; it is put back even if a check fails.
    env.clock.now = new Date('2026-08-15T20:00:00Z');
    try {
      const late = await createPipeline(env.deps).run('manual');
      expect(late.stats!.expired).toBeGreaterThan(0);
      expect(env.store.countOpportunities(env.clock.now).suitable).toBe(0);
      expect(env.store.listApplications({ status: ['needs_input', 'ready'] })).toHaveLength(0);
      expect(appFor(env, 'Cemetery Grounds').status).toBe('expired');
      // What was already sent stays sent.
      expect(env.store.getApplication(sentId)!.status).toBe('submitted');
      expect(env.store.listEvents(200).some((e) => e.kind === 'expired')).toBe(true);
    } finally {
      env.clock.now = NOW;
    }
  });
});

