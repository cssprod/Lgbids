import { createServer, type AddressInfo } from 'node:net';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { simpleParser, type ParsedMail } from 'mailparser';
import { SMTPServer, type SMTPServerAddress } from 'smtp-server';
import { emailSettingsSchema, type Application, type EmailSettings } from '../src/shared/schemas.js';
import { buildSubmissionMail, createMailer, emailConfigured } from '../src/server/submission/email.js';

interface Received {
  from: string;
  rcptTo: string[];
  mail: ParsedMail;
}

const received: Received[] = [];
let server: SMTPServer;
let port = 0;

beforeAll(async () => {
  server = new SMTPServer({
    authOptional: true,
    allowInsecureAuth: true,
    // A plain local connection: no STARTTLS with a self-signed certificate to trip over.
    disabledCommands: ['STARTTLS'],
    logger: false,
    onAuth(auth, _session, cb) {
      if (auth.username === 'bids' && auth.password === 'right-password') cb(null, { user: 'bids' });
      else cb(new Error('Invalid username or password'));
    },
    onRcptTo(address, _session, cb) {
      if (address.address.startsWith('nobody@')) {
        const err = new Error('Mailbox unavailable') as Error & { responseCode: number };
        err.responseCode = 550;
        cb(err);
        return;
      }
      cb();
    },
    onData(stream, session, cb) {
      simpleParser(stream)
        .then((mail) => {
          received.push({
            from: session.envelope.mailFrom ? (session.envelope.mailFrom as SMTPServerAddress).address : '',
            rcptTo: session.envelope.rcptTo.map((r) => r.address),
            mail,
          });
          cb();
        })
        .catch((err: Error) => cb(err));
    },
  });
  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
  port = (server.server.address() as AddressInfo).port;
});

afterAll(async () => {
  await new Promise<void>((resolve) => server.close(() => resolve()));
});

function settings(overrides: Partial<EmailSettings> = {}): EmailSettings {
  return emailSettingsSchema.parse({
    host: '127.0.0.1',
    port,
    secure: false,
    fromName: 'Example Landscaping',
    fromEmail: 'bids@landscaping.example',
    replyTo: 'office@landscaping.example',
    bccSelf: true,
    ...overrides,
  });
}

function application(overrides: Partial<Application> = {}): Application {
  return {
    id: 3,
    opportunityId: 7,
    status: 'ready',
    channel: 'email',
    toEmail: 'bids@city.example',
    ccEmail: 'purchasing@city.example; not-an-address',
    subject: 'Quotation – RFQ 26-140 – Boulevard and Median Landscape Maintenance – Example Landscaping Ltd.',
    body: 'Dear Purchasing:\n\nPlease find our quotation attached.\n\nSincerely,\nSam Patel',
    priceTotal: 18450,
    priceNotes: '',
    includeRates: false,
    checklist: [],
    documentIds: [],
    files: [],
    missing: [],
    autoGenerated: false,
    editedByUser: false,
    submittedAt: null,
    submittedVia: '',
    submissionRef: '',
    error: '',
    notes: '',
    createdAt: '2026-06-15T20:00:00Z',
    updatedAt: '2026-06-15T20:00:00Z',
    ...overrides,
  };
}

/** A port nothing listens on: open one, note it, close it. */
async function closedPort(): Promise<number> {
  const probe = createServer();
  await new Promise<void>((resolve) => probe.listen(0, '127.0.0.1', resolve));
  const p = (probe.address() as AddressInfo).port;
  await new Promise<void>((resolve) => probe.close(() => resolve()));
  return p;
}

const pdf = Buffer.concat([Buffer.from('%PDF-1.4\n'), Buffer.alloc(2048, 0x20), Buffer.from('\n%%EOF\n')]);

describe('emailConfigured', () => {
  it('needs a host, a port and a valid sender address', () => {
    expect(emailConfigured(settings())).toBe(true);
    expect(emailConfigured(settings({ host: '' }))).toBe(false);
    expect(emailConfigured(settings({ fromEmail: 'bids' }))).toBe(false);
    expect(emailConfigured(emailSettingsSchema.parse({}))).toBe(false);
  });
});

describe('buildSubmissionMail', () => {
  it('addresses the buyer, copies cc and blind-copies the sender', () => {
    const mail = buildSubmissionMail({
      app: application(),
      settings: settings(),
      attachments: [{ filename: 'package.pdf', content: pdf, contentType: 'application/pdf' }],
    });
    expect(mail.to).toEqual(['bids@city.example']);
    expect(mail.cc).toEqual(['purchasing@city.example']);
    expect(mail.bcc).toEqual(['bids@landscaping.example']);
    expect(mail.subject).toBe(application().subject);
    expect(mail.text).toBe(application().body);
    expect(buildSubmissionMail({ app: application(), settings: settings({ bccSelf: false }), attachments: [] }).bcc).toEqual([]);
  });

  it('refuses a submission without a valid recipient', () => {
    expect(() => buildSubmissionMail({ app: application({ toEmail: 'buyer at city' }), settings: settings(), attachments: [] })).toThrow(
      'The submission has no valid recipient address.',
    );
  });

  it('refuses attachments over 20 MB with a readable message', () => {
    const big = Buffer.alloc(21 * 1024 * 1024);
    expect(() =>
      buildSubmissionMail({ app: application(), settings: settings(), attachments: [{ filename: 'big.pdf', content: big, contentType: 'application/pdf' }] }),
    ).toThrow(/21\.0 MB, more than the 20 MB/);
  });
});

describe('createMailer', () => {
  it('sends a submission with its attachment over SMTP', async () => {
    const s = settings();
    const mailer = createMailer(s);
    await mailer.verify();
    const mail = buildSubmissionMail({
      app: application(),
      settings: s,
      attachments: [{ filename: 'Example-Landscaping-RFQ-26-140-submission.pdf', content: pdf, contentType: 'application/pdf' }],
    });
    const before = received.length;
    const result = await mailer.send(mail);
    expect(result.messageId).toMatch(/@/);
    expect(received.length).toBe(before + 1);
    const got = received[received.length - 1]!;
    expect(got.from).toBe('bids@landscaping.example');
    expect(got.rcptTo.sort()).toEqual(['bids@city.example', 'bids@landscaping.example', 'purchasing@city.example']);
    expect(got.mail.subject).toBe(application().subject);
    expect(got.mail.from?.value[0]).toMatchObject({ name: 'Example Landscaping', address: 'bids@landscaping.example' });
    expect(got.mail.replyTo?.text).toBe('office@landscaping.example');
    // Blind copies must not show up in the headers the buyer sees.
    expect(got.mail.headers.has('bcc')).toBe(false);
    expect(got.mail.text?.trim()).toBe(application().body);
    expect(got.mail.attachments).toHaveLength(1);
    expect(got.mail.attachments[0]?.filename).toBe('Example-Landscaping-RFQ-26-140-submission.pdf');
    expect(got.mail.attachments[0]?.contentType).toBe('application/pdf');
    expect(got.mail.attachments[0]?.content.equals(pdf)).toBe(true);
  });

  it('logs in when a user name is set', async () => {
    await createMailer(settings({ user: 'bids', pass: 'right-password' })).verify();
  });

  it('reports a wrong password without revealing it', async () => {
    const err = await createMailer(settings({ user: 'bids', pass: 'wrong-secret-123' }))
      .verify()
      .then(() => null, (e: Error) => e);
    expect(err).toBeInstanceOf(Error);
    expect(err!.message).toMatch(/^Authentication failed/);
    expect(err!.message).not.toContain('wrong-secret-123');
  });

  it('reports a refused recipient', async () => {
    const mail = buildSubmissionMail({ app: application({ toEmail: 'nobody@city.example', ccEmail: '' }), settings: settings({ bccSelf: false }), attachments: [] });
    await expect(createMailer(settings()).send(mail)).rejects.toThrow(/refused the recipient address/);
  });

  it('fails when the buyer is refused even though the copy to ourselves was accepted', async () => {
    const mail = buildSubmissionMail({ app: application({ toEmail: 'nobody@city.example', ccEmail: '' }), settings: settings(), attachments: [] });
    expect(mail.bcc).toEqual(['bids@landscaping.example']);
    await expect(createMailer(settings()).send(mail)).rejects.toThrow('The mail server refused the recipient address (nobody@city.example).');
  });

  it('says it could not connect when nothing is listening', async () => {
    const p = await closedPort();
    await expect(createMailer(settings({ port: p })).verify()).rejects.toThrow(`Could not connect to the mail server at 127.0.0.1:${p}`);
  });
});
