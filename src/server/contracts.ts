export interface SendResult {
  ok: boolean;
  /** Why it was not sent, in plain language. */
  error: string;
}

export interface SourceTestResult {
  status: SourceStatus;
  message: string;
  ms: number;
  count: number;
  /** First few notices as read, for checking by eye. */
  sample: { title: string; url: string; organization: string; closesAt: string | null; closingRaw: string; referenceNumber: string }[];
  requests: { url: string; status: number | null; bytes: number; ms: number; error?: string }[];
}

export interface Pipeline {
  /** Run discover → analyse → draft → send. Resolves with the finished run. Rejects if one is already running. */
  run(trigger: RunRecord['trigger']): Promise<RunRecord>;
  isRunning(): boolean;
  /** Read one source without saving anything. */
  testSource(source: SourceRecord): Promise<SourceTestResult>;
  /** Re-analyse one opportunity now and (re)draft its application if appropriate. */
  refreshOpportunity(id: number): Promise<void>;
  /** Create (or rebuild, when `rebuild`) the application for an opportunity the user chose to pursue. */
  draftFor(opportunityId: number, opts: { rebuild: boolean }): Application;
  /** Recompute `missing` and needs_input/ready after the user edited an application. */
  reassess(applicationId: number): Application;
  /** Send an e-mail submission. `auto` applies the automatic-mode guardrails as well. */
  send(applicationId: number, opts: { auto: boolean }): Promise<SendResult>;
  /** The submission package PDF for an application. */
  packagePdf(applicationId: number): Promise<{ filename: string; content: Buffer }>;
}

export interface Scheduler {
  start(): void;
  stop(): void;
  /** Call after automation settings change. */
  reschedule(): void;
  nextRunAt(): string | null;
}

/** What the pipeline read from one award or result notice. */
export interface ParsedAwardInput {
  /** The bid it is about (canonical), when found. */
  originalId: number | null;
  /** The award or result notice row, when it is a row of its own. */
  noticeId: number | null;
  winner: string;
  amount: number | null;
  amountText: string;
  awardedOn: string | null;
  excerpt: string;
  /** Result notices without a winner only close the bid; award notices mark it awarded. */
  awarded: boolean;
}
