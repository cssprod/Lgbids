/** An opportunity with the internal fields the pipeline needs. */
export interface OpportunityRecord extends Opportunity {
  noticeTypeHint: string;
  /** Text read from publicly linked bid documents. */
  documentText: string;
  bcSource: boolean;
  detailFetchedAt: string | null;
  documentsReadAt: string | null;
  analysedAt: string | null;
  notifiedAt: string | null;
}

export interface UpsertResult {
  id: number;
  isNew: boolean;
  /** Something the analysis depends on changed. */
  changed: boolean;
  closingChanged: boolean;
}

export interface AnalysisSave {
  noticeType: NoticeType;
  score: number;
  decision: Decision;
  analysis: Analysis;
  submissionMethod: SubmissionMethod;
  submissionEmail: string;
  submissionUrl: string;
  /** Fills contact_email only when it is empty. */
  contactEmail?: string;
}

export type OpportunityView = 'suitable' | 'review' | 'unsuitable' | 'closed' | 'dismissed' | 'all';

export interface OpportunityFilter {
  view?: OpportunityView;
  q?: string;
  sourceId?: string;
  /** Only notices closing between now and this many days from now. */
  closingWithinDays?: number;
  /** Suitability score at least this (0–100); unscored notices are left out. */
  minScore?: number;
  /** Only notices whose analysis found this service. */
  service?: ServiceKey;
  /** Contained in the analysis area match or the location, ignoring case. */
  place?: string;
  limit?: number;
  offset?: number;
}

export interface ApplicationCreate {
  opportunityId: number;
  status: ApplicationStatus;
  channel: ApplicationChannel;
  toEmail: string;
  ccEmail: string;
  subject: string;
  body: string;
  includeRates: boolean;
  checklist: ChecklistItem[];
  documentIds: number[];
  missing: string[];
  autoGenerated: boolean;
}

export type ApplicationPatch = Partial<
  Pick<
    Application,
    | 'status'
    | 'channel'
    | 'toEmail'
    | 'ccEmail'
    | 'subject'
    | 'body'
    | 'priceTotal'
    | 'priceNotes'
    | 'includeRates'
    | 'checklist'
    | 'documentIds'
    | 'missing'
    | 'editedByUser'
    | 'submittedAt'
    | 'submittedVia'
    | 'submissionRef'
    | 'error'
    | 'notes'
  >
> & { remindedAt?: string | null };

/** What is stored for a new change row. */
export type NoticeChangeCreate = Omit<NoticeChange, 'id' | 'notifiedAt' | 'seenAt'>;

/** Feedback as saved; `opportunityId` null is a bid Lgbids missed. */
export type FeedbackSave = Omit<FeedbackRecord, 'id' | 'createdAt'>;

/** An award as saved; with an `opportunityId` it replaces that bid's award. */
export type AwardSave = Omit<Award, 'id' | 'updatedAt'>;

export interface ReminderRecord {
  opportunityId: number;
  thresholdHours: number;
  /** The closing instant the reminder was for, so a moved date re-arms it. */
  closesAt: string;
  sentAt: string;
  /** Channels that went through, e.g. ['push', 'email']. */
  channels: string[];
}

export interface StoredFile {
  storedName: string;
  name: string;
  mime: string;
  size: number;
}

export interface Store {
  // settings (raw JSON values; use SettingsService for typed access)
  getSetting(key: string): unknown | undefined;
  setSetting(key: string, value: unknown, now: Date): void;

  // sources
  listSources(): SourceRecord[];
  getSource(id: string): SourceRecord | undefined;
  insertSource(input: { id: string; name: string; kind: SourceKind; enabled: boolean; builtin: boolean; notes: string; config: SourceConfig }, now: Date): SourceRecord;
  updateSource(id: string, patch: Partial<Pick<SourceRecord, 'name' | 'enabled' | 'notes' | 'config'>>, now: Date): SourceRecord | undefined;
  deleteSource(id: string): boolean;
  /**
   * Insert any default source that is not there yet (`enabled: false` starts
   * it off). For built-in sources already there, refresh the note, and turn
   * off one marked `forceOff` (a site that refuses automated reading); the
   * user's on/off choice for every other source is kept. The name and config
   * are replaced with the new default only while the stored config still
   * equals the default it was seeded with, so a fix reaches existing installs
   * but a source the user edited keeps their settings. User-added sources are
   * never touched.
   */
  seedSources(defaults: { id: string; name: string; kind: SourceKind; notes: string; config: SourceConfig; enabled?: boolean; forceOff?: boolean }[], now: Date): void;
  /** Also keeps the "layout may have changed" warning up to date; `raised` is true on the run that first set it. */
  recordSourceRun(
    id: string,
    result: { status: SourceStatus; message: string; itemCount: number | null; unchanged?: boolean; incremental?: boolean },
    now: Date,
  ): { layoutWarning: string; raised: boolean };
  /** A "Test" that listed notices shows the reader still works. */
  clearLayoutWarning(id: string): void;
  getSourceState(id: string): Record<string, unknown>;
  setSourceState(id: string, state: Record<string, unknown>): void;
  clearSourceStates(): void;

  // opportunities
  /** Also returns the changes the write recorded (saved in `opportunity_changes`). */
  upsertOpportunity(sourceId: string, raw: RawOpportunity, bcSource: boolean, now: Date): UpsertResult & { changes: NoticeChange[] };
  /** Merge a notice page's details into the row (longer description wins, empty fields are filled) and stamp detail_fetched_at. */
  applyDetail(id: number, detail: Partial<RawOpportunity> | null, now: Date): { closingChanged: boolean; changes: NoticeChange[] };
  setDocumentText(id: number, text: string, now: Date): void;
  saveAnalysis(id: number, result: AnalysisSave, now: Date): void;
  /**
   * Link this opportunity to the same notice from another source, if there is one
   * (same buyer + reference, or same buyer + title with closings within 36 hours).
   * The older row stays canonical; its empty fields are filled from the newer one.
   * Returns the canonical id when a link was made.
   */
  linkDuplicate(id: number): number | null;
  /**
   * Open rows of one source whose notice page was last read before `readBefore`
   * and whose bid is watched (D12: pursued, or with an application that needs
   * input, is ready or was submitted). Copies of a watched bid count too. Oldest read first.
   */
  watchedForRefetch(sourceId: string, readBefore: string, limit: number): { id: number; raw: RawOpportunity }[];
  /**
   * The bid an award or result notice is about: same reference or title key,
   * the same source allowed, never another award or result notice. Canonical id, or null.
   */
  findAwardOriginal(noticeId: number): number | null;
  /**
   * Record what an award notice says. A linked original becomes `awarded`; the
   * values are saved as a `suggested` award, never over a confirmed or hand-entered one.
   */
  recordParsedAward(input: ParsedAwardInput, now: Date): Award | null;
  getOpportunity(id: number): OpportunityRecord | undefined;
  /** Canonical rows only (duplicate_of IS NULL), each with its application summary. */
  listOpportunities(filter: OpportunityFilter, now: Date): { items: OpportunityRecord[]; total: number };
  countOpportunities(now: Date): Record<OpportunityView, number>;
  /** Other sources' rows linked to this canonical row. */
  duplicatesOf(id: number): { sourceName: string; url: string }[];
  setUserDecision(id: number, decision: UserDecision): void;
  /** Open, canonical rows that need (re)analysis: never analysed, or changed since. */
  opportunitiesToAnalyse(): OpportunityRecord[];
  /** Mark every open, canonical row for re-analysis (after profile or settings change). */
  markAllForAnalysis(): void;
  /** Mark open rows whose closing instant has passed as closed; returns their ids. */
  closeExpired(now: Date): number[];
  markNotified(ids: number[], now: Date): void;

  // applications
  createApplication(data: ApplicationCreate, now: Date): Application;
  getApplication(id: number): Application | undefined;
  getApplicationByOpportunity(opportunityId: number): Application | undefined;
  /** Each with its opportunity attached. Newest first. */
  listApplications(filter: { status?: ApplicationStatus[] }): Application[];
  updateApplication(id: number, patch: ApplicationPatch, now: Date): Application | undefined;
  /**
   * Atomically move an application from one of `from` to `to`. Returns false
   * (and changes nothing) when its status is not in `from`. This is what
   * guarantees a submission is never sent twice.
   */
  transitionApplication(id: number, from: ApplicationStatus[], to: ApplicationStatus, now: Date): boolean;
  countSubmittedSince(sinceIso: string, autoOnly: boolean): number;
  addApplicationFile(applicationId: number, file: StoredFile, now: Date): ApplicationFile;
  getApplicationFile(applicationId: number, fileId: number): (ApplicationFile & { storedName: string }) | undefined;
  listApplicationFiles(applicationId: number): (ApplicationFile & { storedName: string })[];
  deleteApplicationFile(applicationId: number, fileId: number): string | null;

  // document library
  addDocument(doc: StoredFile & { kind: DocumentKind; filename: string; expiresOn: string; attachByDefault: boolean }, now: Date): LibraryDocument;
  listDocuments(): LibraryDocument[];
  getDocument(id: number): (LibraryDocument & { storedName: string }) | undefined;
  updateDocument(id: number, patch: Partial<Pick<LibraryDocument, 'name' | 'kind' | 'expiresOn' | 'attachByDefault'>>): LibraryDocument | undefined;
  deleteDocument(id: number): string | null;

  // runs & events
  startRun(trigger: RunRecord['trigger'], now: Date): RunRecord;
  finishRun(id: number, status: RunRecord['status'], stats: RunStats | null, error: string, now: Date): RunRecord;
  /** Runs left "running" by a crash are marked as errors. */
  failStaleRuns(now: Date): void;
  latestRun(): RunRecord | undefined;
  listRuns(limit: number): RunRecord[];
  addEvent(event: Omit<EventRecord, 'id' | 'at'> , now: Date): void;
  listEvents(limit: number): EventRecord[];
  /** Delete events and finished runs older than the given instant, so the database does not grow forever. */
  pruneHistory(beforeIso: string): { events: number; runs: number };

  // v2: watching bids and their changes
  setAlertsMuted(opportunityId: number, muted: boolean): boolean;
  addChange(change: NoticeChangeCreate): NoticeChange;
  /** Newest first. */
  listChanges(opportunityId: number): NoticeChange[];
  /** Oldest first, every opportunity. */
  unnotifiedChanges(): NoticeChange[];
  markChangesNotified(ids: number[], now: Date): void;
  /** Returns how many were newly marked. */
  markChangesSeen(opportunityId: number, now: Date): number;
  /** Unseen, non-silent changes on canonical rows. */
  countUnseenChanges(): number;

  // v2: closing reminders
  reminderSent(opportunityId: number, thresholdHours: number, closesAt: string): boolean;
  recordReminder(reminder: ReminderRecord): void;
  listReminders(opportunityId: number): ReminderRecord[];

  // v2: feedback (one per opportunity; saving again replaces it)
  saveFeedback(feedback: FeedbackSave, now: Date): FeedbackRecord;
  getFeedback(id: number): FeedbackRecord | undefined;
  getFeedbackFor(opportunityId: number): FeedbackRecord | undefined;
  deleteFeedbackFor(opportunityId: number): boolean;
  /** Newest first. */
  listFeedback(filter?: { sinceIso?: string }): FeedbackRecord[];

  // v2: awards (one per opportunity)
  saveAward(award: AwardSave, now: Date): Award;
  getAwardFor(opportunityId: number): Award | undefined;
  deleteAwardFor(opportunityId: number): boolean;
  listAwards(): Award[];

  // v2: saved searches (names unique ignoring case)
  listSavedSearches(): SavedSearch[];
  getSavedSearch(id: number): SavedSearch | undefined;
  /** Null when the name is already taken. */
  createSavedSearch(input: SavedSearchInput, now: Date): SavedSearch | null;
  /** Undefined when not found; null when the new name is already taken. */
  updateSavedSearch(id: number, patch: SavedSearchPatch): SavedSearch | null | undefined;
  deleteSavedSearch(id: number): boolean;

  // v2: alert recipients
  listRecipients(): Recipient[];
  getRecipient(id: number): Recipient | undefined;
  createRecipient(input: RecipientInput, now: Date): Recipient;
  updateRecipient(id: number, patch: RecipientPatch): Recipient | undefined;
  deleteRecipient(id: number): boolean;
  markRecipientVerified(id: number, now: Date): void;

  // v2: meta values (e.g. keys_version)
  getMeta(key: string): string | undefined;
  setMeta(key: string, value: string): void;

  // sessions
  createSession(token: string, expiresAt: Date, now: Date): void;
  sessionValid(token: string, now: Date): boolean;
  deleteSession(token: string): void;
  /** Sign everyone out (after a password change). Returns how many were removed. */
  deleteAllSessions(): number;

  close(): void;
}

export interface SettingsService {
  getProfile(): Profile;
  setProfile(value: unknown): Profile;
  getAutomation(): AutomationSettings;
  setAutomation(value: unknown): AutomationSettings;
  /** Stored settings overlaid with SMTP_* environment variables. */
  getEmail(): EmailSettings;
  /** An empty `pass` keeps the stored password. */
  setEmail(value: unknown): EmailSettings;
  getRegion(): RegionSettings;
  setRegion(value: unknown): RegionSettings;
  getAlertInbox(): AlertInboxSettings;
  /** An empty `pass` keeps the stored password; changing the connection clears `verifiedAt`. */
  setAlertInbox(value: unknown): AlertInboxSettings;
  /** Record a successful connection test. */
  markAlertInboxVerified(at: Date): void;
  getPush(): PushSettings;
  /** Empty tokens keep the saved ones; a new ntfy server forgets the ntfy token; changes clear `verifiedAt`. */
  setPush(value: unknown, opts?: { removeNtfyToken?: boolean }): PushSettings;
  /** Record a test alert that went through. */
  markPushVerified(at: Date): void;
  resetRegion(): RegionSettings;
}

/** Uploaded files on disk under <dataDir>/files. Names are generated, never user-supplied. */
export interface FileStore {
  save(content: Buffer, originalName: string): Promise<string>;
  read(storedName: string): Promise<Buffer>;
  remove(storedName: string): Promise<void>;
}

