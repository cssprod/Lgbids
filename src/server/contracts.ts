/**
 * The seams between the server's modules. Each module is written against
 * these interfaces only, so the parts can be built and tested separately.
 */

// ---------------------------------------------------------------------------
// Configuration
// ---------------------------------------------------------------------------

export interface AppConfig {
  port: number;
  host: string;
  /** Folder holding the database and uploaded files. */
  dataDir: string;
  /** When set, the web UI and API require this password. */
  appPassword: string;
  /** Zone used to show and interpret local times. */
  timeZone: string;
  /** Demo mode: invented sample sites, mail goes to a local sink. */
  demo: boolean;
  /** Folder with the built web UI, or '' when not built. */
  webDir: string;
  /**
   * Host names the server answers to (Host header), against DNS rebinding.
   * Undefined or empty = this computer's names and the bind address only.
   */
  allowedHosts?: string[];
  /** Fastify `trustProxy`: true/false, a hop count, or addresses / CIDR ranges of trusted proxies. */
  trustProxy?: boolean | number | string | string[];
  /** Log file path; '' = log to stdout only. Undefined = the default for the environment. */
  logFile?: string;
}

