import { DateTime } from 'luxon';
import type { Application, ApplicationChannel, ChecklistItem, Profile, Requirement } from '../../shared/schemas.js';
import type { ApplicationCreate, DraftContext, OpportunityRecord, Readiness } from '../contracts.js';
import { emailConfigured } from '../submission/email.js';
import { closingDeadline } from '../util/dates.js';
import { collapse, isEmail, parseEmailList, truncate } from '../util/text.js';
import { companyName, NO_PRICE_TYPES, noticeLine, packageFilename, submissionWord, transmittalText } from './templates.js';

/**
 * Turning an opportunity into a draft submission, and deciding whether that
 * draft can go out. Pure: everything it needs arrives in the arguments.
 *
 * A draft is "ready" only when nothing on the missing list remains. The list
 * is written for the user, one thing to do per line.
 */

/** Profile fields no submission can go out without. Empty = complete. */
export function profileGaps(profile: Profile): string[] {
  const gaps: string[] = [];
  if (!profile.legalName) gaps.push("Add the company's legal name.");
  if (!profile.addressLine || !profile.city) gaps.push("Add the company's mailing address (street and city).");
  if (!profile.phone) gaps.push('Add a phone number.');
  if (!profile.email) gaps.push("Add the company's e-mail address.");
  else if (!isEmail(profile.email)) gaps.push("Correct the company's e-mail address; it is not a valid address.");
  if (!profile.contactName) gaps.push('Add the name of the contact person.');
  return gaps;
}

function channelFor(opp: OpportunityRecord): ApplicationChannel {
  switch (opp.submissionMethod) {
    case 'email':
      return isEmail(opp.submissionEmail) ? 'email' : 'manual';
    case 'bonfire':
    case 'bcbid':
    case 'bidsandtenders':
    case 'portal':
      return 'portal';
    default:
      return 'manual';
  }
}

function needsPrice(opp: OpportunityRecord): boolean {
  const pricing = opp.analysis?.pricing ?? 'unknown';
  return (pricing === 'lump_sum' || pricing === 'unknown') && !NO_PRICE_TYPES.includes(opp.noticeType);
}

function hasRates(profile: Profile): boolean {
  return profile.rates.some((r) => r.label);
}

function todayIn(zone: string, now: Date): string {
  return DateTime.fromJSDate(now).setZone(zone).toISODate() ?? now.toISOString().slice(0, 10);
}

/** One checklist row per requirement found in the notice; null for those that need no row. */
function checklistRow(req: Requirement): Omit<ChecklistItem, 'key'> | null {
  switch (req.key) {
    case 'site_meeting': {
      const mandatory = /^mandatory/i.test(req.label);
      return mandatory
        ? { label: 'I attended the mandatory site meeting', detail: req.detail, done: false, required: true }
        : { label: 'Site meeting: check whether attendance is required', detail: req.detail, done: false, required: false };
    }
    case 'bid_bond':
      return { label: 'Bid bond or bid security obtained and attached', detail: req.detail, done: false, required: true };
    case 'forms':
      return { label: "Buyer's forms completed and attached", detail: req.detail, done: false, required: true };
    case 'insurance':
    case 'worksafe':
    case 'business_licence':
    case 'certification':
    case 'references':
      return { label: req.label, detail: req.detail, done: req.met === true, required: false };
    case 'performance_bond':
    case 'security_clearance':
    case 'questions_deadline':
      return { label: req.label, detail: req.detail, done: false, required: false };
    case 'pricing':
      // Covered by the standing pricing item below.
      return null;
    default:
      return null;
  }
}

function buildChecklist(opp: OpportunityRecord): ChecklistItem[] {
  const out: ChecklistItem[] = [];
  const seen = new Map<string, number>();
  for (const req of opp.analysis?.requirements ?? []) {
    const row = checklistRow(req);
    if (!row) continue;
    // Keys must stay the same when a draft is rebuilt, so the user's ticks survive.
    const n = (seen.get(req.key) ?? 0) + 1;
    seen.set(req.key, n);
    out.push({ key: n === 1 ? req.key : `${req.key}_${n}`, ...row });
  }
  out.push({ key: 'documents', label: 'I have read the bid documents and any addenda', detail: '', done: false, required: true });
  if (needsPrice(opp)) {
    out.push({ key: 'pricing', label: 'Price entered and checked against the bid documents', detail: '', done: false, required: true });
  }
  return out;
}

function subjectFor(opp: OpportunityRecord, profile: Profile): string {
  const parts = [submissionWord(opp.noticeType), noticeLine(opp), companyName(profile)].map(collapse).filter(Boolean);
  return truncate(parts.join(' – '), 300);
}

export function draftApplication(opp: OpportunityRecord, ctx: DraftContext): Omit<ApplicationCreate, 'opportunityId' | 'autoGenerated'> {
  const { profile } = ctx;
  const channel = channelFor(opp);
  const toEmail = channel === 'email' ? opp.submissionEmail.trim().toLowerCase() : '';
  const includeRates = opp.analysis?.pricing === 'rates' && hasRates(profile);

  const today = todayIn(ctx.zone, ctx.now);
  const docs = ctx.documents.filter((d) => d.attachByDefault && (!d.expiresOn || d.expiresOn >= today));
  const attachmentNames = [packageFilename(opp, profile), ...docs.map((d) => d.filename || d.name)];

  const subject = subjectFor(opp, profile);
  const body = transmittalText(opp, profile, { priceTotal: null, includeRates, attachmentNames });
  const checklist = buildChecklist(opp);

  const readiness = assessReadiness({ channel, toEmail, priceTotal: null, includeRates, checklist, subject, body }, opp, ctx);
  return {
    status: readiness.status,
    channel,
    toEmail,
    ccEmail: '',
    subject,
    body,
    includeRates,
    checklist,
    documentIds: docs.map((d) => d.id),
    missing: readiness.missing,
  };
}

export function assessReadiness(
  app: Pick<Application, 'channel' | 'toEmail' | 'priceTotal' | 'includeRates' | 'checklist' | 'subject' | 'body'>,
  opp: OpportunityRecord,
  ctx: DraftContext,
): Readiness {
  const missing: string[] = [];

  for (const gap of profileGaps(ctx.profile)) missing.push(`Company profile: ${gap.charAt(0).toLowerCase()}${gap.slice(1)}`);

  for (const item of app.checklist) {
    if (item.required && !item.done) missing.push(item.label);
  }

  const pricing = opp.analysis?.pricing ?? 'unknown';
  if (pricing === 'rates') {
    if (!hasRates(ctx.profile)) missing.push('Add your rates to the company profile.');
  } else if (needsPrice(opp) && !(app.priceTotal !== null && app.priceTotal > 0)) {
    missing.push('Enter the total price.');
  }

  // Portal and hard-copy submissions are uploaded or delivered by the user,
  // so only e-mail submissions depend on the address and the mail settings.
  if (app.channel === 'email') {
    if (parseEmailList(app.toEmail).length === 0) missing.push("Enter the buyer's submission e-mail address.");
    if (!app.subject.trim()) missing.push('Enter a subject line for the e-mail.');
    if (!app.body.trim()) missing.push('Write the e-mail message.');
    if (!emailConfigured(ctx.email)) missing.push('Outgoing e-mail is not set up yet.');
  }

  const closed =
    opp.status !== 'open' ||
    (opp.closesAt !== null && ctx.now.getTime() >= closingDeadline(opp.closesAt, opp.closesAtPrecision, ctx.zone).getTime());
  if (closed) missing.push('This opportunity has closed.');

  return { status: missing.length ? 'needs_input' : 'ready', missing };
}

/** Rebuilt drafts keep whatever the user already ticked or unticked. */
export function mergeChecklist(previous: ChecklistItem[], next: ChecklistItem[]): ChecklistItem[] {
  const ticks = new Map(previous.map((item) => [item.key, item.done]));
  return next.map((item) => {
    const done = ticks.get(item.key);
    return done === undefined ? item : { ...item, done };
  });
}
